#!/usr/bin/env node
/**
 * Regenerates packages/client/src/generated/registry.ts from the Worker's
 * GET /corpus/registry, which is the one source of truth for which corpora
 * exist, how the hub groups them, what they are called, and which live APIs
 * sit beside them. The app imports the generated module, so the corpus list,
 * the CorpusSlug type, the hub groups and the labels cannot drift from the
 * Worker: a hand edit here is overwritten, and a stale file fails the drift
 * test (app/src/spokes/registry-drift.test.ts).
 *
 *   npm run registry:sync                      # from the live Worker
 *   npm run registry:sync -- --source <file>   # from a saved response (development)
 *   npm run registry:sync -- --check           # write nothing; exit 1 if the file is stale
 *
 * The live call is slow when the Worker's edge cache is cold (about 9s), and a
 * deploy does not purge that cache, so the URL carries a throwaway `fresh`
 * parameter that always misses it.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(HERE, '../src/generated/registry.ts')
const DEFAULT_URL = 'https://ragtimeproxy.benjamin-wittes.workers.dev'

const args = process.argv.slice(2)
const sourceIdx = args.indexOf('--source')
const source = sourceIdx >= 0 ? args[sourceIdx + 1] : null
const checkOnly = args.includes('--check')

async function load() {
  if (source) return JSON.parse(readFileSync(source, 'utf8'))
  const url = `${DEFAULT_URL}/corpus/registry?fresh=${Date.now()}`
  let lastError = ''
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const r = await fetch(url, { signal: AbortSignal.timeout(30_000) })
      if (!r.ok) throw new Error(`HTTP ${r.status}`)
      return await r.json()
    } catch (e) {
      lastError = e instanceof Error ? e.message : String(e)
      console.error(`registry:sync attempt ${attempt} failed: ${lastError}`)
    }
  }
  throw new Error(`could not read ${url}: ${lastError}`)
}

function need(cond, message) {
  if (!cond) throw new Error(`registry response is not what the app expects: ${message}`)
}

const q = (s) => JSON.stringify(s)

function render(reg) {
  need(Array.isArray(reg.corpora) && reg.corpora.length > 0, 'no corpora[]')
  need(reg.hub && Array.isArray(reg.hub.groups), 'no hub.groups[] (is the Worker on a version with #161?)')
  need(Array.isArray(reg.live_apis), 'no live_apis[]')
  const slugs = new Set(reg.corpora.map((c) => c.slug))
  for (const c of reg.corpora) {
    need(typeof c.name === 'string' && c.name, `${c.slug} has no name`)
    need(typeof c.short_name === 'string' && c.short_name, `${c.slug} has no short_name (is the Worker on a version with #162?)`)
    need(c.hub === null || (c.hub && c.hub.group && c.hub.title), `${c.slug} has a malformed hub`)
  }
  for (const g of reg.hub.groups) for (const s of g.corpora) need(slugs.has(s), `hub group ${g.id} names unknown corpus ${s}`)

  const lines = []
  lines.push('// GENERATED by packages/client/scripts/sync-registry.mjs from GET /corpus/registry.')
  lines.push('// Do not edit by hand: regenerate with `npm run registry:sync`. Staleness fails')
  lines.push('// app/src/spokes/registry-drift.test.ts. Coverage figures are left out on purpose;')
  lines.push('// they change with every ingest and the app reads them live.')
  lines.push('')
  lines.push(`export const REGISTRY_VERSION = ${q(reg.version)} as const`)
  lines.push('')
  lines.push('/** Every corpus the Worker registry holds, in registry order. */')
  lines.push('export const CORPORA = [')
  for (const c of reg.corpora) {
    const hub = c.hub === null ? 'null' : `{ group: ${q(c.hub.group)}, order: ${c.hub.order}, title: ${q(c.hub.title)} }`
    lines.push(`  { slug: ${q(c.slug)}, name: ${q(c.name)}, shortName: ${q(c.short_name)}, kind: ${q(c.kind)}, hub: ${hub} },`)
  }
  lines.push('] as const')
  lines.push('')
  lines.push('/** The hub layout: headings in page order, each with its corpus slugs in card order. */')
  lines.push('export const HUB_GROUPS = [')
  for (const g of reg.hub.groups) {
    lines.push(`  { id: ${q(g.id)}, heading: ${q(g.heading)}, corpora: [${g.corpora.map(q).join(', ')}] },`)
  }
  lines.push('] as const')
  lines.push('')
  lines.push('/** Sources read live from someone else\'s API. Not corpora: nothing here is held. */')
  lines.push('export const LIVE_APIS = [')
  for (const a of reg.live_apis) {
    lines.push(`  { slug: ${q(a.slug)}, name: ${q(a.name)}, description: ${q(a.description)} },`)
  }
  lines.push('] as const')
  lines.push('')
  return lines.join('\n')
}

const next = render(await load())
let current = ''
try { current = readFileSync(OUT, 'utf8') } catch { /* first run */ }

if (checkOnly) {
  if (current === next) { console.log('registry:sync --check: generated registry is current'); process.exit(0) }
  console.error('registry:sync --check: generated registry is STALE. Run `npm run registry:sync` and commit the result.')
  process.exit(1)
}
mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, next)
console.log(current === next ? 'registry:sync: already current' : `registry:sync: wrote ${OUT}`)
